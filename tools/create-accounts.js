#!/usr/bin/env node
// Creates the starting accounts for a Meadow House installation.
//
//   node tools/create-accounts.js accounts.input.json
//
// accounts.input.json: [{ "name": "…", "email": "…", "role": "staff|maintenance|manager|admin" }, …]
// The initial password is taken from the INITIAL_PASSWORD environment variable, or generated.
//
// Writes two files that are git-ignored and must never be published:
//   accounts.local.js    – salted PBKDF2-SHA-256 hashes only (loaded by the sign-in page)
//   ACCOUNTS-PRIVATE.md  – names, emails, roles and the initial password, for the administrator
"use strict";
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const ITERATIONS = 600000;
const ROLES = { staff: "Care staff", maintenance: "Maintenance team", manager: "Home manager", admin: "System administrator" };
const root = path.resolve(__dirname, "..");
const inputPath = path.resolve(process.argv[2] || path.join(root, "accounts.input.json"));

function fail(message) {
  console.error(`Error: ${message}`);
  process.exit(1);
}

function generatePassword() {
  const words = ["Bluebell", "Lantern", "Harbour", "Willow", "Copper", "Thistle", "Orchard", "Granite", "Kestrel", "Juniper", "Saffron", "Heather"];
  const pick = () => words[crypto.randomInt(words.length)];
  let a = pick(), b = pick();
  while (b === a) b = pick();
  return `${a}-${b}-${crypto.randomInt(1000, 9999)}`;
}

let people;
try {
  people = JSON.parse(fs.readFileSync(inputPath, "utf8"));
} catch (error) {
  fail(`could not read ${inputPath}: ${error.message}`);
}
if (!Array.isArray(people) || !people.length) fail("the input file must be a non-empty list of people.");
const seen = new Set();
people.forEach((p, i) => {
  if (!p.name || !p.email || !ROLES[p.role]) fail(`entry ${i + 1} needs a name, an email and a role (${Object.keys(ROLES).join(", ")}).`);
  const key = p.email.toLowerCase();
  if (seen.has(key)) fail(`${p.email} appears twice.`);
  seen.add(key);
});
if (!people.some((p) => p.role === "admin")) fail("include at least one administrator.");

const password = process.env.INITIAL_PASSWORD || generatePassword();
if (password.length < 12) fail("INITIAL_PASSWORD must be at least 12 characters.");

const accounts = people.map((p) => {
  const salt = crypto.randomBytes(16);
  const hash = crypto.pbkdf2Sync(password, salt, ITERATIONS, 32, "sha256");
  return {
    id: `u-${p.name.toLowerCase().replace(/[^a-z]+/g, "-").replace(/^-|-$/g, "")}`,
    name: p.name.trim(), email: p.email.trim().toLowerCase(), role: p.role,
    salt: salt.toString("base64"), hash: hash.toString("base64"), iterations: ITERATIONS
  };
});

fs.writeFileSync(path.join(root, "accounts.local.js"),
  `// Starting accounts for this installation. Generated by tools/create-accounts.js on ${new Date().toISOString().slice(0, 10)}.\n` +
  "// Contains password hashes only. Do not publish this file (it is listed in .gitignore).\n" +
  `window.MH_SEED_ACCOUNTS = ${JSON.stringify(accounts, null, 2)};\n`);

const byRole = (role) => people.filter((p) => p.role === role);
const lines = [
  "# Meadow House – starting accounts (PRIVATE)",
  "",
  "> Keep this file private. It is listed in `.gitignore` and must never be committed, emailed in full or shared publicly.",
  "> Give each person their sign-in name and the initial password separately and in private (in person or by phone).",
  "",
  `Generated: ${new Date().toISOString().slice(0, 10)}`,
  "",
  `**Initial password (all accounts): \`${password}\`**`,
  "",
  "Everyone must choose their own password the first time they sign in. After that the initial password no longer works for their account.",
  ""
];
Object.entries(ROLES).reverse().forEach(([role, label]) => {
  const list = byRole(role);
  if (!list.length) return;
  lines.push(`## ${label}`, "", "| Name | Email (can be used to sign in) |", "|---|---|");
  list.forEach((p) => lines.push(`| ${p.name} | ${p.email} |`));
  lines.push("");
});
lines.push(
  "## How these accounts are loaded",
  "",
  "`accounts.local.js` (in the same folder as `login.html`) creates these accounts the first time the system is opened in a browser.",
  "If the system is hosted, upload `accounts.local.js` together with the other files, but never add it to the public repository.",
  "Without the file, the system starts with a first-time set-up screen for creating the administrator account.",
  "",
  "To change the list: edit `accounts.input.json`, then run `node tools/create-accounts.js accounts.input.json` again."
);
fs.writeFileSync(path.join(root, "ACCOUNTS-PRIVATE.md"), `${lines.join("\n")}\n`);
console.log(`Created ${accounts.length} accounts. Wrote accounts.local.js and ACCOUNTS-PRIVATE.md (both git-ignored).`);
